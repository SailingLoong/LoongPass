#!/usr/bin/env python3
"""Generate the native/Flutter bridge constants; JSON is the sole owner."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    contract = json.loads((ROOT / 'tool/update_contract.json').read_text())
    constants = [('channel', contract['channel'])] + [
        (name, name) for group in ('fields', 'methods') for name in contract[group]]
    phases = contract['phases']
    banner = '// Generated by tool/update_contract.py. Do not edit.\n'
    dart = banner + 'abstract final class UpdateContract {\n' + ''.join(
        f"  static const {name} = '{value}';\n" for name, value in constants) + '}\n\n'
    dart += 'enum UpdatePhase {\n' + ''.join(f'  {phase},\n' for phase in phases) + '}\n'
    swift = banner + 'enum UpdateContract {\n' + ''.join(
        f'  static let {name} = "{value}"\n' for name, value in constants) + '}\n\n'
    swift += 'enum UpdatePhase: String {\n  case ' + ', '.join(phases) + '\n}\n'
    cpp = banner + '#pragma once\nnamespace loongpass::update {\n' + ''.join(
        f'inline constexpr char {name}[] = "{value}";\n' for name, value in constants)
    cpp += 'namespace phases {\n' + ''.join(f'inline constexpr char {name}[] = "{name}";\n' for name in phases) + '}\n}\n'
    return {'lib/update_contract.dart': dart, 'macos/Runner/UpdateContract.swift': swift,
            'windows/runner/update_contract.h': cpp}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, value in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit('Stale update contract: ' + name)
        else:
            path.write_text(value)
